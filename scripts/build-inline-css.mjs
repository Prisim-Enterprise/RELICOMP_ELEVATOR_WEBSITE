import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import autoprefixer from "autoprefixer";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/generated");
const cssPath = join(outDir, "inlined.css");

mkdirSync(outDir, { recursive: true });

execSync(
  "node_modules/.bin/tailwindcss -i ./app/globals.css -o ./src/generated/inlined.css --minify",
  { cwd: root, stdio: "inherit" }
);

const compiled = readFileSync(cssPath, "utf8");
const prefixed = await postcss([autoprefixer]).process(compiled, {
  from: undefined,
});

writeFileSync(
  join(outDir, "inlined-css.ts"),
  `/* Generated by scripts/build-inline-css.mjs. Do not edit. */\nexport const inlinedCss = ${JSON.stringify(prefixed.css)};\n`
);
